"""Small independent release-lifecycle acceptance interface; no physics runner.

Actual implementation tests use a caller-supplied pure harness. Self-tests only
validate these checkers and never claim acceptance of an absent controller.
All outputs belong under review/. Core/evaluation/protocol files stay untouched.
"""
from pathlib import Path
from datetime import datetime,timezone
from copy import deepcopy
import ast,hashlib,json,argparse
import numpy as np

ROOT=Path(__file__).resolve().parents[1]


def sha(path):return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def verify_source_freeze(expected,root=ROOT):
    differences=[]
    for name,wanted in expected.items():
        path=Path(name);path=path if path.is_absolute() else Path(root)/path
        if not path.is_file() or sha(path)!=wanted:differences.append(name)
    return dict(passed=not differences,checked=len(expected),differences=differences)


def verify_command_envelope(before,after,lower,upper,max_rate,dt,tolerance=1e-9):
    values=[np.asarray(x,float) for x in (before,after,lower,upper,max_rate)]
    before,after,lower,upper,rate=values
    shapes=all(x.shape==before.shape for x in values) and before.ndim==1
    finite=shapes and all(np.isfinite(x).all() for x in values) and np.isfinite(dt) and dt>0
    return dict(passed=bool(finite and np.all(lower<=upper) and np.all(rate>=0) and
        np.all(after>=lower-tolerance) and np.all(after<=upper+tolerance) and np.all(abs(after-before)<=rate*dt+tolerance)),
        finite=bool(finite),scope='Actual actuator command target and per-tick command-rate bounds; measured joint limits are checked separately.')


def verify_joint_measurements(position,velocity,lower,upper,speed_limit,tolerance=0.):
    q=np.asarray(position,float);v=np.asarray(velocity,float);lo=np.asarray(lower,float);hi=np.asarray(upper,float);rate=np.asarray(speed_limit,float)
    valid=q.shape==v.shape and q.ndim==2 and lo.shape==hi.shape==rate.shape==(q.shape[1],) and all(np.isfinite(x).all() for x in (q,v,lo,hi,rate))
    if not valid:return dict(passed=False,reason='missing_or_invalid_measured_joint_contract')
    outside=(q<lo-tolerance)|(q>hi+tolerance);fast=abs(v)>rate+tolerance
    return dict(passed=bool(not outside.any() and not fast.any()),out_of_range_samples=int(outside.any(axis=1).sum()),
        speed_violation_samples=int(fast.any(axis=1).sum()),tolerance=float(tolerance),
        scope='True encoder measurements against explicitly supplied physical limits. No command-as-measurement substitution or invented physical speed threshold.')


def verify_release_preemption(harness,frames):
    """harness.step(frame,release_requested)->normalized output mapping.

    Required output: mode, holding_called, monitoring_active, clear_confirmed;
    optional actuator fields use verify_command_envelope. The harness wraps the
    real decoder/runtime with a holding-controller spy; it must not infer spy
    counts merely from the requested mode string.
    """
    if len(frames)<3:raise ValueError('Need hold, request and post-request frames')
    outputs=[]
    for i,frame in enumerate(frames):outputs.append(harness.step(deepcopy(frame),release_requested=(i==1)))
    allowed={'release','releasing','cleared','monitoring','release_monitor','release_recontact'}
    checks=dict(release_enters_on_first_requested_tick=outputs[1]['mode'] in allowed,
        holding_canceled_on_request=not outputs[1]['holding_called'],
        no_holding_until_explicit_reset=all(not r['holding_called'] for r in outputs[1:]),
        release_mode_latched=all(r['mode'] in allowed for r in outputs[1:]))
    envelopes=[]
    for row in outputs[1:]:
        fields=('actuator_before','actuator_target','actuator_lower','actuator_upper','actuator_max_rate','dt')
        if all(k in row for k in fields):envelopes.append(verify_command_envelope(*(row[k] for k in fields)))
    checks['all_supplied_actual_command_envelopes']=all(v['passed'] for v in envelopes)
    checks['command_envelope_was_supplied']=bool(envelopes)
    clear=next((i for i,r in enumerate(outputs) if r['clear_confirmed']),None)
    checks['monitoring_continues_after_clear']=clear is not None and all(r['monitoring_active'] for r in outputs[clear:])
    return dict(passed=all(checks.values()),checks=checks,outputs=outputs,
        scope='Pure real-harness integration test; no simulator or user command is generated by this checker.')


def verify_public_identity_invariance(factory,frames,output_projection):
    """Identical public measurements, different forbidden identity diagnostics."""
    first=factory();second=factory();same=True
    for i,frame in enumerate(frames):
        a=deepcopy(frame);b=deepcopy(frame)
        # Diagnostic labels are deliberately irrelevant. Physical/tactile/
        # encoder fields and task commands are identical in both streams.
        a['diagnostic_identity']={'target_id':1,'is_target':True,'true_mass':.12,'true_friction':.6}
        b['diagnostic_identity']={'target_id':987,'is_target':False,'true_mass':9.,'true_friction':.01}
        x=output_projection(first.step(a,release_requested=i==1));y=output_projection(second.step(b,release_requested=i==1))
        same &= np.array_equal(np.asarray(x),np.asarray(y),equal_nan=True)
    return dict(passed=bool(same),scope='Dynamic forbidden-diagnostic invariance test; supplements source/interface review and is not a complete information-flow proof.')


def static_information_scan(path):
    forbidden={'is_target','target_id','target_geom_id','object_pose','true_mass','true_friction'}
    found=[]
    for node in ast.walk(ast.parse(Path(path).read_text(encoding='utf-8'))):
        if isinstance(node,ast.Attribute) and node.attr in forbidden:found.append((node.lineno,node.attr))
        if isinstance(node,ast.Subscript) and isinstance(node.slice,ast.Constant) and node.slice.value in forbidden:found.append((node.lineno,node.slice.value))
    return dict(passed=not found,reads=found,source_sha256=sha(path),
        scope='Controller-only candidate read scan; evaluation truth use must be audited separately.')


def verify_baseline_unchanged(old_trace,new_trace,new_release_enabled=False):
    if new_release_enabled:raise ValueError('Baseline regression must explicitly disable the new release path')
    names=('time','qpos','qvel','ctrl','alpha','normal','skin_normal','requested_action','executed_action',
        'observed_normal','validity','all_hand_object','substep_time','substep_duration','substep_skin_normal','substep_all_hand_object')
    with np.load(old_trace,allow_pickle=False) as a,np.load(new_trace,allow_pickle=False) as b:
        checks={k:(k in a.files and k in b.files and np.array_equal(a[k],b[k],equal_nan=True)) for k in names}
    return dict(passed=all(checks.values()),checks=checks,old_sha256=sha(old_trace),new_sha256=sha(new_trace),
        scope='Exact saved physical/action/observed trajectory regression with the new release disabled; wall-clock diagnostics excluded.')


def _dwell(t,flag,start,end,duration):
    since=None
    for i in np.flatnonzero((t>=start-1e-9)&(t<=end+1e-9)):
        if flag[i]:
            since=float(t[i]) if since is None else since
            if t[i]-since>=duration-1e-9:return float(t[i])
        else:since=None
    return None


def postclear_recontact(trace,metadata,threshold=.2,dwell=.2,deadline=3.5,duration=16.):
    """Additional truth-only description; never replaces safety/release guards."""
    t=np.asarray(trace['time'],float);force=np.asarray(trace['all_hand_object'],float)
    release=metadata.get('release_at');complete=bool(len(t)>1 and abs(t[-1]-duration)<1e-8 and np.isfinite(force).all() and np.allclose(np.diff(t),.005,atol=1e-8,rtol=0))
    result=dict(actual_release_at=release,clear_confirmed_at=None,complete_remaining_observation=complete,
        release_postclear_recontact=None,postclear_at_risk_s=None,first_recontact_latency_s=None,postclear_peak_N=None,
        scope='Additional descriptive target-object truth after physical clearance; not controller input, not whole-task safety, not a replacement release-success definition.')
    if release is None:return result
    clear=_dwell(t,force<=threshold,float(release),min(duration,float(release)+deadline),dwell)
    result['clear_confirmed_at']=clear
    if clear is None or not complete:return result
    if all(k in trace for k in ('substep_time','substep_duration','substep_all_hand_object')):
        # Saved interval starts carry the force solved at each interval end.
        starts=np.asarray(trace['substep_time']);dur=np.asarray(trace['substep_duration'])
        sf=np.asarray(trace['substep_all_hand_object'])
        raw_complete=bool(starts.ndim==1 and dur.shape==sf.shape==starts.shape and len(starts)>0 and
            np.isfinite(starts).all() and np.isfinite(dur).all() and np.isfinite(sf).all() and (dur>0).all() and
            abs(starts[0])<1e-8 and abs(starts[-1]+dur[-1]-duration)<1e-8 and
            np.allclose(np.diff(starts),dur[:-1],atol=1e-8,rtol=0))
        result['raw_followup_complete']=raw_complete
        if not raw_complete:
            result.update(complete_remaining_observation=False,recontact_sampling='incomplete/nonfinite raw physical coverage; rate contribution is null')
            return result
        st=starts+dur
        mask=(st>clear+1e-9)&(st<=duration+1e-8)
        times=st[mask];values=sf[mask];sampling='all raw physical interval-end force samples'
        # Include terminal truth as an instantaneous endpoint, not an interval.
        times=np.r_[times,t[-1]];values=np.r_[values,force[-1]]
    else:
        result['raw_followup_complete']=None
        mask=t>clear+1e-9;times=t[mask];values=force[mask];sampling='200Hz truth only; raw substep recontact coverage unavailable'
    hit=np.flatnonzero(values>threshold)
    result.update(release_postclear_recontact=bool(len(hit)),postclear_at_risk_s=float(duration-clear),
        first_recontact_latency_s=float(times[hit[0]]-clear) if len(hit) else None,
        postclear_peak_N=float(values.max()) if len(values) else 0.,recontact_sampling=sampling)
    return result


def summarize_recontact(records):
    eligible=[r for r in records if r['release_postclear_recontact'] is not None]
    return dict(assigned_release_records=len(records),cleared_with_complete_followup=len(eligible),
        release_postclear_recontacts=sum(r['release_postclear_recontact'] for r in eligible),
        release_postclear_recontact_rate=float(np.mean([r['release_postclear_recontact'] for r in eligible])) if eligible else None,
        observation_seconds=[r['postclear_at_risk_s'] for r in eligible],
        interpretation='Conditional on confirmed clearance and complete remaining followup; unequal followup durations are displayed, absent/uncleared/censored is not zero.')


def self_test():
    checks={}
    checks['command_bound_and_rate_ok']=verify_command_envelope([0.],[.01],[-1.],[1.],[2.],.005)['passed']
    checks['command_jump_rejected']=not verify_command_envelope([0.],[.02],[-1.],[1.],[2.],.005)['passed']
    checks['command_limit_rejected']=not verify_command_envelope([.99],[1.01],[-1.],[1.],[10.],.005)['passed']
    checks['measured_joint_not_command_proxy']=not verify_joint_measurements([[1.1]],[[0.]],[-1.],[1.],[1.])['passed']
    t=np.arange(3201)*.005;force=np.full(len(t),2.);force[t>=12.2]=0.;force[(t>=14.)&(t<14.1)]=1.
    record=postclear_recontact(dict(time=t,all_hand_object=force),dict(release_at=12.))
    checks['recontact_monitored_after_clear']=record['release_postclear_recontact'] is True and abs(record['clear_confirmed_at']-12.4)<1e-8
    checks['first_recontact_time']=abs(record['first_recontact_latency_s']-1.6)<1e-8
    incomplete=postclear_recontact(dict(time=t[:-1],all_hand_object=force[:-1]),dict(release_at=12.))
    checks['incomplete_followup_is_null']=incomplete['release_postclear_recontact'] is None
    never=postclear_recontact(dict(time=t,all_hand_object=np.full(len(t),2.)),dict(release_at=12.))
    checks['never_clear_is_null_not_false']=never['release_postclear_recontact'] is None
    checks['no_clearance_denominator_not_zero_rate']=summarize_recontact([never])['release_postclear_recontact_rate'] is None
    broken=postclear_recontact(dict(time=t,all_hand_object=force,substep_time=np.array([0.,15.]),
        substep_duration=np.array([.005,.005]),substep_all_hand_object=np.array([2.,0.])),dict(release_at=12.))
    checks['raw_gap_not_reported_as_no_recontact']=broken['release_postclear_recontact'] is None and broken['raw_followup_complete'] is False
    return dict(passed=all(checks.values()),checks=checks,implementation_validation='pending actual release-controller/runtime harness; these are checker self-tests only')


def main():
    parser=argparse.ArgumentParser();parser.add_argument('--self-test',action='store_true');parser.add_argument('--trace');parser.add_argument('--out')
    args=parser.parse_args()
    if args.self_test:result=self_test()
    elif args.trace:
        path=Path(args.trace)
        with np.load(path,allow_pickle=False) as a:
            names=('time','all_hand_object','substep_time','substep_duration','substep_all_hand_object')
            trace={k:a[k] for k in names if k in a.files};metadata=json.loads(str(a['metadata']))
        sidecar=path.with_name('metadata.json')
        if sidecar.exists():metadata.update(json.loads(sidecar.read_text(encoding='utf-8')))
        result=postclear_recontact(trace,metadata);result['trace_sha256']=sha(path)
    else:parser.error('Choose --self-test or an already saved --trace; this tool never runs physics')
    result.update(created_utc=datetime.now(timezone.utc).isoformat(),verifier_sha256=sha(__file__))
    if args.out:
        output=Path(args.out).resolve()
        if not output.is_relative_to(ROOT/'review') or output.exists():raise ValueError('Choose a fresh review-only output')
        output.parent.mkdir(parents=True,exist_ok=True);output.write_text(json.dumps(result,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    print(json.dumps(result,ensure_ascii=False))


if __name__=='__main__':main()
