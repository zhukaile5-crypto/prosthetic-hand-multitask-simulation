"""Freeze a development-selected implementation before fresh confirmation."""
from pathlib import Path
import argparse, datetime, json, shutil
import numpy as np
from run_experiments import ROOT, METHODS, BENCHMARK_ID, hashes, sha, dump
from scenarios import SCENARIOS

def main():
    ap=argparse.ArgumentParser();ap.add_argument('--development-prefix',required=True);ap.add_argument('--preflight',required=True);args=ap.parse_args()
    destination=ROOT/'review'/'confirmation_plan.json'
    if destination.exists():raise RuntimeError('A confirmation plan already exists; preserve it and create a distinct study')
    settings=json.loads((ROOT/'settings.json').read_text(encoding='utf-8'))
    selection_path=ROOT/settings['selection_source'];selection=json.loads(selection_path.read_text(encoding='utf-8'))
    if selection['prefix']!=args.development_prefix or sha(selection_path)!=settings['selection_sha256'] or selection['formal_data_used']:
        raise ValueError('Selection provenance differs')
    if selection['development_inputs']['code_sha256']!=hashes():raise ValueError('Code differs from candidate development')
    physical=json.loads((ROOT/'review'/'physical_acceptance.json').read_text(encoding='utf-8'))
    preflight=json.loads((ROOT/args.preflight).read_text(encoding='utf-8'))
    evaluation=json.loads((ROOT/'review'/'evaluation_verification.json').read_text(encoding='utf-8'))
    controller=json.loads((ROOT/'controller_verification.json').read_text(encoding='utf-8'))
    if not physical['foundation']['accepted'] or physical['physics_sha256']!=hashes()['physics.py'] or not preflight['passed'] or not evaluation['passed'] or not controller['passed']:
        raise ValueError('Acceptance evidence not complete')
    if preflight['runtime_sha256']!=hashes() or preflight.get('formal_seeds_used',False):
        raise ValueError('Preflight does not verify the final exact implementation')
    snapshot=ROOT/'review'/'frozen_sources';snapshot.mkdir()
    support=('settings.json','controller_candidates.json','实施与实验协议.md','controller_implementation.md','controller_v2_model.md','README.md','analyze.py','plot_results.py','select_development.py','freeze_confirmation.py','assemble_results.py','reproduce_all.ps1','replay_snapshot.py')
    for name in (*hashes().keys(),*support):shutil.copy2(ROOT/name,snapshot/name)
    evidence_paths=[selection_path,ROOT/args.preflight,ROOT/'review'/'physical_acceptance.json',ROOT/'review'/'evaluation_verification.json',ROOT/'controller_verification.json',ROOT/'review'/'selected_controller_step_sensitivity.json',ROOT/'review'/'ratio_time_alignment_contract.json',ROOT/'review'/'development_record_integrity.json',ROOT/'output'/'final_all_scenario_development'/'execution_complete.json']
    # Development-only variance of seed-paired main endpoints. Three clusters
    # cannot establish a reliable power model; fresh samples are initial evidence.
    chosen={}
    for method in ('ratio','unified'):
        i=selection['selected'][method]['index']
        rows=json.loads((ROOT/'output'/f'{args.development_prefix}_{i}'/'trials.json').read_text(encoding='utf-8'))
        chosen[method]={(r['scenario'],r['seed']):r for r in rows if r['method']==method}
    precision={}
    for endpoint in ('restricted_unstable_time','finger_tv_rate'):
        groups={}
        for key,a in chosen['unified'].items():
            b=chosen['ratio'][key]
            if endpoint=='finger_tv_rate':
                if not (a['static_window']['eligible'] and b['static_window']['eligible']):continue
                difference=a['static_window']['metrics'][endpoint]-b['static_window']['metrics'][endpoint]
            else:difference=a[endpoint]-b[endpoint]
            groups.setdefault(key[1],[]).append(difference)
        values=np.array([np.mean(v) for v in groups.values()])
        sd=float(np.std(values,ddof=1)) if len(values)>1 else None
        precision[endpoint]=dict(development_clusters=len(values),paired_cluster_sd=sd,
            approximate_95_halfwidth_test=None if sd is None else 1.96*sd/np.sqrt(12),
            approximate_95_halfwidth_robustness=None if sd is None else 1.96*sd/np.sqrt(8),
            caution='three development clusters and changed robustness domain cannot establish reliable power; use confirmation CI and report inconclusive gates')
    plan=dict(created_utc=datetime.datetime.now(datetime.timezone.utc).isoformat(),
        benchmark_id=BENCHMARK_ID,full_shadow_dynamics=False,code_sha256=hashes(),settings_sha256=sha(ROOT/'settings.json'),
        supporting_sha256={name:sha(ROOT/name) for name in support},
        evidence_sha256={str(p.relative_to(ROOT)):sha(p) for p in evidence_paths},
        source_model_sha256=sha(ROOT.parent/'五指假肢抓握仿真'/'model.xml'),
        source_model_scope='archived Shadow asset provenance; current parameterized model generated by frozen physics.py',
        model_metadata=physical['model_metadata'],physics_timestep=.0005,decision_timestep=.020,execution_timestep=.005,
        methods=list(METHODS),scenarios=[s.name for s in SCENARIOS],test_seeds=list(range(13101,13113)),robustness_seeds=list(range(14101,14109)),
        expected_test_trials=1344,expected_robustness_trials=896,total_confirmation_trials=2240,
        primary_comparison='unified versus ratio',primary_endpoints=['restricted_unstable_time','static.finger_tv_rate'],
        multiplicity='two-endpoint Holm within each parameter domain; sensitivity and ablation exploratory',bootstrap_replicates=5000,
        gate_margins=dict(task_success=-.05,force_protection_pass=-.05,release_success=-.05,static_coverage=-.05,local_excess_integral=.02,total_excess_integral=.02),
        development_precision=precision,no_confirmation_data_used=True,retuning_after_confirmation=False)
    dump(destination,plan);print(json.dumps(dict(frozen=str(destination),trials=2240,precision=precision),ensure_ascii=False))

if __name__=='__main__':main()
