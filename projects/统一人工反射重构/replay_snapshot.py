"""Render saved runner configurations without advancing dynamics or controllers.

Examples::
  python replay_snapshot.py --source output/run/traces/nominal__ratio__13101.npz \
      --times 8.5 9.3 --outfolder review/replay_validation
  python replay_snapshot.py --source FIRST.npz SECOND.npz --gif \
      --start 0 --stop 12 --fps 8 --outfolder review/replay_validation/paired

Only qpos/mocap snapshots are replayed. Saved trace forces are annotations;
forces generated by mj_forward are never used as reconstructed measurements.
"""
from __future__ import annotations

import argparse
from dataclasses import fields
import hashlib
import json
import math
from pathlib import Path
import sys
import time

import mujoco
import numpy as np
from PIL import Image, ImageDraw, ImageFont

from physics import Plant
from scenarios import Scenario

ROOT = Path(__file__).resolve().parent
MODEL_ID = 'mujoco_finite_mass_five_compliant_contacts_v1'
BG = '#f5f8fa'
INK = '#17343d'
MUTED = '#536c76'


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def font(size):
    for name in ['C:/Windows/Fonts/msyh.ttc', 'C:/Windows/Fonts/simhei.ttf',
                 'C:/Windows/Fonts/arial.ttf']:
        if Path(name).exists():
            return ImageFont.truetype(name, size)
    return ImageFont.load_default()


def manifest_for(source):
    for folder in [source.parent, source.parent.parent]:
        path = folder/'manifest.json'
        if path.is_file():
            return path, json.loads(path.read_text(encoding='utf-8-sig'))
    return None, {}


class Replay:
    def __init__(self, source, width=700, height=520):
        self.source = Path(source).resolve()
        self.source_sha = sha(self.source)
        with np.load(self.source, allow_pickle=False) as saved:
            self.meta = json.loads(str(saved['metadata']))
            needed = ['time', 'qpos', 'mocap_pos', 'normal', 'position']
            missing = [k for k in needed if k not in saved.files]
            if missing:
                raise ValueError(f'Missing runner snapshot fields: {missing}')
            self.trace = {k: saved[k].copy() for k in needed}
            for optional in ['mocap_quat', 'phase', 'alpha', 'rotation']:
                if optional in saved.files:
                    self.trace[optional] = saved[optional].copy()
        self.times = np.asarray(self.trace['time'], dtype=float)
        if self.times.ndim != 1 or len(self.times) < 1 or not np.all(np.isfinite(self.times)):
            raise ValueError('Snapshot time must be a nonempty finite vector.')
        if np.any(np.diff(self.times) <= 0):
            raise ValueError('Snapshot times must increase strictly.')
        if self.meta.get('benchmark_id') != MODEL_ID:
            raise ValueError('This renderer only accepts the declared finite-mass five-pad benchmark.')
        self.manifest_path, manifest = manifest_for(self.source)
        expected = self.meta.get('physics_sha256') or manifest.get('code_sha256', {}).get('physics.py')
        self.physics_sha = sha(ROOT/'physics.py')
        if expected and expected != self.physics_sha:
            raise ValueError(f'Physics source mismatch: trace {expected}, current {self.physics_sha}.')
        self.source_verified = bool(expected)
        declared = self.meta['scenario']
        names = {f.name for f in fields(Scenario)}
        scenario = Scenario(**{k: v for k, v in declared.items() if k in names})
        self.plant = Plant(scenario, self.meta['parameters'], self.meta['physics_timestep'])
        self.model, self.data = self.plant.model, self.plant.data
        if self.trace['qpos'].shape != (len(self.times), self.model.nq):
            raise ValueError('Saved qpos dimension differs from the reconstructed public model.')
        if self.trace['mocap_pos'].shape != (len(self.times), self.model.nmocap, 3):
            raise ValueError('Saved mocap position dimension differs from the public model.')
        if self.model.nmocap and 'mocap_quat' not in self.trace:
            raise ValueError('Mocap orientation is missing; the full visual state cannot be certified.')
        self.width, self.height = width, height
        # Rendering buffer size is visual configuration, not a physics edit.
        self.model.vis.global_.offwidth = max(width, self.model.vis.global_.offwidth)
        self.model.vis.global_.offheight = max(height, self.model.vis.global_.offheight)
        self.renderer = mujoco.Renderer(self.model, height=height, width=width)
        self.camera = mujoco.MjvCamera()
        self.camera.type = mujoco.mjtCamera.mjCAMERA_FREE
        self.index = None
        self.checks = []

    def select(self, requested):
        requested = float(requested)
        if requested < self.times[0]-1e-10 or requested > self.times[-1]+1e-10:
            raise ValueError(f'Requested {requested:g}s is outside saved interval {self.times[0]:g}..{self.times[-1]:g}s.')
        index = int(np.argmin(np.abs(self.times-requested)))
        self.data.qpos[:] = self.trace['qpos'][index]
        self.data.qvel[:] = 0.  # Runner stores configurations, not generalized velocities.
        self.data.mocap_pos[:] = self.trace['mocap_pos'][index]
        if 'mocap_quat' in self.trace:
            self.data.mocap_quat[:] = self.trace['mocap_quat'][index]
        self.data.time = float(self.times[index])
        mujoco.mj_forward(self.model, self.data)
        position_error = float(np.max(np.abs(self.data.xpos[self.plant.object]-self.trace['position'][index])))
        qpos_error = float(np.max(np.abs(self.data.qpos-self.trace['qpos'][index])))
        if qpos_error > 1e-12 or position_error > 1e-8:
            raise ValueError(f'Reconstructed configuration differs: qpos {qpos_error}, object position {position_error}.')
        self.index = index
        record = {'requested_time_s': requested, 'saved_time_s': float(self.times[index]),
                  'snapshot_index': index, 'object_position_max_error_m': position_error,
                  'qpos_max_error': qpos_error,
                  'saved_object_position_m': self.trace['position'][index].tolist(),
                  'saved_normal_force_N': self.trace['normal'][index].tolist()}
        self.checks.append(record)
        return record

    def project(self, point):
        left, right = self.renderer.scene.camera
        eye = (np.asarray(left.pos)+np.asarray(right.pos))/2.
        forward = np.asarray(left.forward)
        up = np.asarray(left.up)
        across = np.cross(forward, up)
        relative = np.asarray(point)-eye
        depth = float(relative@forward)
        if depth <= 0:
            return None
        scale = self.height/(2*math.tan(math.radians(self.model.vis.global_.fovy)/2))
        return self.width/2+scale*float(relative@across)/depth, self.height/2-scale*float(relative@up)/depth

    def panel(self, top=False, annotate=True):
        if self.index is None:
            raise ValueError('Select a saved snapshot before rendering.')
        center = self.data.xpos[self.plant.object].copy()
        # Object-centred view keeps released objects visible; each is explicitly labeled.
        self.camera.lookat[:] = center
        self.camera.distance = .35 if top else .43
        self.camera.azimuth = 90 if top else 135
        self.camera.elevation = -90 if top else -28
        self.renderer.update_scene(self.data, camera=self.camera)
        pixels = self.renderer.render().copy()
        panel = Image.fromarray(pixels)
        draw = ImageDraw.Draw(panel)
        draw.rounded_rectangle((12, 12, 270, 49), radius=8, fill=(245, 248, 250))
        draw.text((22, 18), '俯视 Top view' if top else '斜视 Oblique view', fill=INK, font=font(21))
        if top and annotate:
            screen_center = self.project(center)
            for digit, geom in enumerate(self.plant.pad_geoms):
                point = self.project(self.data.geom_xpos[geom])
                if point is None:
                    continue
                direction = np.asarray(point)-np.asarray(screen_center)
                direction /= max(np.linalg.norm(direction), 1e-12)
                endpoint = np.asarray(point)+direction*39
                text = f'P{digit}  {self.trace["normal"][self.index,digit]:.2f} N'
                text_font = font(18)
                bbox = draw.textbbox((0, 0), text, font=text_font)
                tw, th = bbox[2]-bbox[0], bbox[3]-bbox[1]
                x = float(endpoint[0]-tw/2)
                y = float(endpoint[1]-th/2)
                draw.line((point[0], point[1], endpoint[0], endpoint[1]), fill=INK, width=2)
                draw.rounded_rectangle((x-5, y-3, x+tw+5, y+th+7), radius=4, fill=(245, 248, 250))
                draw.text((x, y-3), text, fill=INK, font=text_font)
        if annotate:
            # Draw world-coordinate directions from real camera projection; annotations only.
            origin = center+np.array([-.07, -.07, -.075])
            projected = self.project(origin)
            if projected:
                anchor = np.array([64., self.height-40.])
                draw.text((20, self.height-145), '世界轴方向 / World axes', fill=INK, font=font(16))
                for axis, color in [(0, '#b83c45'), (1, '#287f51'), (2, '#356ab8')]:
                    end = origin.copy(); end[axis] += .025
                    e = self.project(end)
                    if e:
                        direction = (np.asarray(e)-np.asarray(projected))*1.5
                        endpoint = anchor+direction
                        draw.line((*anchor, *endpoint), fill=color, width=3)
                        draw.ellipse((endpoint[0]-3, endpoint[1]-3, endpoint[0]+3, endpoint[1]+3), fill=color)
                        draw.text((endpoint[0]+4, endpoint[1]-9), 'XYZ'[axis], fill=color, font=font(17))
        return panel

    def snapshot(self):
        gap, margin, header, footer = 16, 24, 103, 195
        image = Image.new('RGB', (2*self.width+2*margin+gap, self.height+header+footer), BG)
        draw = ImageDraw.Draw(image)
        method = self.meta['method']
        title = f'保存状态回放 / Saved-state replay — {method}'
        draw.text((margin, 15), title, font=font(28), fill=INK)
        draw.text((margin, 59), f'{self.meta["scenario"]["title"]}  |  seed {self.meta["seed"]}  |  t = {self.times[self.index]:.3f} s',
                  font=font(21), fill=MUTED)
        image.paste(self.panel(False), (margin, header))
        image.paste(self.panel(True), (margin+self.width+gap, header))
        y = header+self.height+14
        position = self.trace['position'][self.index]
        lines = [
            '五个有质量柔顺接触垫 + 自由刚体 / Five finite-mass compliant pads + free rigid object',
            f'物体世界坐标 [m] / World position: [{position[0]:+.5f}, {position[1]:+.5f}, {position[2]:+.5f}]',
            '坐标轴与 P0–P4 为图像标记；N 值来自保存轨迹 / Axes and labels are overlays; force values are recorded.',
            '仅恢复 qpos / mocap 并进行几何渲染；未重跑控制或动力学 / No controller or dynamics simulation.',
            '此画面展示公共基准与轨迹，不单独证明算法优劣 / Visualization does not establish comparative efficacy.',
            f'来源 / Source: {self.source.name}  |  physics SHA256: {self.physics_sha[:16]}…',
        ]
        for line in lines:
            draw.text((margin, y), line, font=font(17), fill=MUTED)
            y += 28
        return image

    def close(self):
        self.renderer.close()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', nargs='+', required=True, type=Path)
    parser.add_argument('--times', nargs='+', type=float, default=[8.5, 9.3])
    parser.add_argument('--outfolder', type=Path, required=True)
    parser.add_argument('--gif', action='store_true', help='Also produce a paired or single saved-state animation.')
    parser.add_argument('--start', type=float, default=0.)
    parser.add_argument('--stop', type=float, default=12.)
    parser.add_argument('--fps', type=int, default=8)
    args = parser.parse_args()
    args.outfolder.mkdir(parents=True, exist_ok=True)
    certificate_path = args.outfolder/'replay_validation.json'
    if certificate_path.exists():
        parser.error('Output validation exists; choose a new output folder to preserve replay evidence.')
    report = {'schema': 'saved-runner-configuration-render-v1', 'status': 'running',
              'renderer_version': mujoco.__version__, 'script_sha256': sha(__file__),
              'requested_sources': [str(p.resolve()) for p in args.source],
              'no_dynamics_steps': True, 'no_controller_calls': True,
              'state_schema': {'qpos': 'MuJoCo generalized configuration in model joint order',
                               'mocap_pos': 'world coordinates in m; empty in current public benchmark',
                               'normal': 'saved object-specific pad forces in N; never inferred by replay',
                               'time': 'nearest saved control snapshot, no interpolation'},
              'limitations': ['Generalized velocity is not saved; zero qvel is used for geometric forwarding only.',
                              'Rendered force labels come from the trace, not mj_forward contact forces.',
                              'The renderer uses object-centred cameras and visual labels only.',
                              'This evidence does not establish algorithm efficacy or full Shadow hand validation.'],
              'sources': [], 'images': [], 'elapsed_seconds': None}
    replays = []
    started = time.perf_counter()
    try:
        for source in args.source:
            replay = Replay(source)
            replays.append(replay)
            entry = {'path': str(replay.source), 'trace_sha256_before': replay.source_sha,
                     'physics_sha256': replay.physics_sha, 'source_sha_verified': replay.source_verified,
                     'manifest_path': str(replay.manifest_path) if replay.manifest_path else None,
                     'benchmark_id': replay.meta['benchmark_id'], 'method': replay.meta['method'],
                     'scenario': replay.meta['scenario'], 'parameters': replay.meta['parameters'],
                     'physics_timestep_s': replay.meta['physics_timestep'],
                     'model_dimensions': {'nq': replay.model.nq, 'nv': replay.model.nv, 'nmocap': replay.model.nmocap},
                     'snapshots': replay.checks}
            report['sources'].append(entry)
            for requested in args.times:
                selected = replay.select(requested)
                path = args.outfolder/f'{replay.source.stem}__t{selected["saved_time_s"]:.3f}.png'
                replay.snapshot().save(path)
                report['images'].append({'path': str(path.resolve()), 'sha256': sha(path)})
        if args.gif:
            if not 1 <= args.fps <= 20 or args.stop <= args.start:
                raise ValueError('GIF requires 1<=fps<=20 and stop>start.')
            if (args.stop-args.start)*args.fps > 240:
                raise ValueError('GIF is limited to 240 frames; shorten interval or lower fps.')
            frames = []
            # GIF panels use the same true renderer, then resize for memory and portability.
            for moment in np.arange(args.start, args.stop+1e-9, 1./args.fps):
                panels = []
                for replay in replays:
                    replay.select(moment)
                    panels.append(replay.snapshot().resize((740, 409), Image.Resampling.LANCZOS))
                frame = Image.new('RGB', (740*len(panels), 409), BG)
                for j, panel in enumerate(panels):
                    frame.paste(panel, (740*j, 0))
                frames.append(frame)
            gifpath = args.outfolder/('paired_saved_state_replay.gif' if len(replays)>1 else 'saved_state_replay.gif')
            frames[0].save(gifpath, save_all=True, append_images=frames[1:], duration=round(1000/args.fps), loop=0)
            report['gif'] = {'path': str(gifpath.resolve()), 'sha256': sha(gifpath),
                             'fps': args.fps, 'frame_count': len(frames), 'start_s': args.start, 'stop_s': args.stop}
        for entry, replay in zip(report['sources'], replays):
            entry['trace_sha256_after'] = sha(replay.source)
            entry['trace_unchanged'] = entry['trace_sha256_after'] == replay.source_sha
            if not entry['trace_unchanged']:
                raise RuntimeError('Source trace changed while rendering.')
        report['status'] = 'rendered'
    except Exception as error:
        report['status'] = 'blocked'
        report['error'] = {'class': type(error).__name__, 'message': str(error)}
        report['limitations'].append('Rendering failure is reported; no substitute scene is generated.')
    finally:
        for replay in replays:
            replay.close()
        report['elapsed_seconds'] = time.perf_counter()-started
        certificate_path.write_text(json.dumps(report, ensure_ascii=False, indent=2)+'\n', encoding='utf-8')
    print(json.dumps({'status': report['status'], 'validation': str(certificate_path.resolve()),
                      'images': len(report['images']), 'error': report.get('error')}, ensure_ascii=True))
    return 0 if report['status'] == 'rendered' else 1


if __name__ == '__main__':
    sys.exit(main())
